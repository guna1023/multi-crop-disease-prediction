"""
app.py
------
Streamlit web application for the AI-Based Multi-Crop Disease Detection
project. Runs 100% locally.

RUN WITH:
    streamlit run app.py
"""

import os

import numpy as np
import streamlit as st
from PIL import Image, UnidentifiedImageError
from tensorflow import keras

from utils_common import load_class_names, parse_class_name, get_disease_info

MODELS_DIR = "models"
BEST_MODEL_PATH = os.path.join(MODELS_DIR, "best_model.keras")
CLASS_NAMES_PATH = os.path.join(MODELS_DIR, "class_names.json")
IMG_SIZE = (224, 224)

st.set_page_config(
    page_title="Multi-Crop Disease Detector",
    page_icon="🌿",
    layout="centered",
)


# ---------------------------------------------------------------------------
# Cached loaders so the model is loaded only ONCE, not on every interaction
# ---------------------------------------------------------------------------
@st.cache_resource
def load_trained_model():
    if not os.path.exists(BEST_MODEL_PATH):
        return None
    return keras.models.load_model(BEST_MODEL_PATH)


@st.cache_resource
def load_classes():
    if not os.path.exists(CLASS_NAMES_PATH):
        return None
    return load_class_names(CLASS_NAMES_PATH)


def preprocess_image(pil_image):
    img = pil_image.convert("RGB").resize(IMG_SIZE)
    array = keras.utils.img_to_array(img)
    array = np.expand_dims(array, axis=0)
    return array


def run_prediction(pil_image, model, class_names):
    img_array = preprocess_image(pil_image)
    predictions = model.predict(img_array, verbose=0)[0]
    predicted_idx = int(np.argmax(predictions))
    confidence = float(predictions[predicted_idx]) * 100
    predicted_class_name = class_names[predicted_idx]
    crop, disease = parse_class_name(predicted_class_name)
    return crop, disease, confidence


# ---------------------------------------------------------------------------
# UI
# ---------------------------------------------------------------------------
st.title("🌿 AI-Based Multi-Crop Disease Detection")
st.write(
    "Upload a **Tomato** or **Corn (Maize)** leaf image, and this app will "
    "predict whether the leaf is healthy or which disease it shows, using a "
    "MobileNetV2 deep learning model trained on local data. "
    "Everything runs locally on your computer — no internet or cloud APIs "
    "are used for prediction."
)

model = load_trained_model()
class_names = load_classes()

if model is None or class_names is None:
    st.error(
        "No trained model found. Please run `python train.py` first to "
        "train a model, then restart this app."
    )
    st.stop()

# Session state controls the "reset" behaviour
if "uploaded_file" not in st.session_state:
    st.session_state.uploaded_file = None

uploaded_file = st.file_uploader(
    "Upload a leaf image (JPG / PNG)",
    type=["jpg", "jpeg", "png"],
    key="file_uploader",
)

col1, col2 = st.columns(2)
predict_clicked = col1.button("🔍 Predict", use_container_width=True)
reset_clicked = col2.button("♻️ Clear / Reset", use_container_width=True)

if reset_clicked:
    st.session_state.uploaded_file = None
    st.rerun()

if uploaded_file is not None:
    try:
        pil_image = Image.open(uploaded_file)
        pil_image.verify()
        uploaded_file.seek(0)
        pil_image = Image.open(uploaded_file)  # re-open after verify()
    except (UnidentifiedImageError, OSError):
        st.error("This file doesn't look like a valid image. Please upload a JPG or PNG leaf photo.")
        st.stop()

    st.image(pil_image, caption="Uploaded Leaf Image", width=700)

    if predict_clicked:
        with st.spinner("Analyzing leaf image..."):
            try:
                crop, disease, confidence = run_prediction(pil_image, model, class_names)
            except Exception as e:
                st.error(f"Something went wrong during prediction: {e}")
                st.stop()

        st.success("Prediction complete!")

        result_col1, result_col2 = st.columns(2)
        result_col1.metric("Crop", crop)
        result_col2.metric("Disease", disease)

        st.progress(min(int(confidence), 100))
        st.write(f"**Confidence:** {confidence:.2f}%")

        if confidence < 60:
            st.warning(
                "Confidence is relatively low. Try a clearer, well-lit, "
                "close-up photo of a single leaf for a more reliable result."
            )

        st.subheader("ℹ️ About this condition")
        st.info(get_disease_info(disease))

elif predict_clicked:
    st.warning("Please upload a leaf image first.")

st.divider()
st.caption(
    "Educational project. Predictions are generated by a machine learning "
    "model and are not a substitute for professional agricultural advice."
)
